//! Yata's wire and file schemas (ADR-0004, ADR-0031).
//!
//! - [`frame`]: the frame codec of the core channel, as `core-protocol.md`, § Frame states it.
//! - [`core`]: the core protocol's messages, generated from `proto/core.proto`: the session,
//!   profiles, queries and pages, scheme-code decoding, and the headless query endpoint.
//! - [`snapshot`]: the yata-snapshot format's messages, generated from `proto/snapshot.proto`,
//!   with their proto3 JSON mapping; [`snapshot_file`]: the file, version first (ADR-0031).
//!
//! The crate is pure and depends on no workspace crate (ADR-0005). It moves bytes between frames,
//! files, and messages and does no I/O: the daemon reads and writes, and feeds the bytes here.

pub mod frame;
pub mod snapshot_file;

/// The yata-snapshot format (`snapshot-ir.md`), generated from `proto/snapshot.proto` at build
/// time.
#[allow(
    clippy::all,
    clippy::pedantic,
    reason = "generated by prost from the schema file"
)]
pub mod snapshot {
    include!(concat!(env!("OUT_DIR"), "/yata.snapshot.v1.rs"));
    include!(concat!(env!("OUT_DIR"), "/yata.snapshot.v1.serde.rs"));

    /// The schema version this build writes (`snapshot-ir.md`, "The `yata-snapshot` file").
    pub const VERSION: SchemaVersion = SchemaVersion { major: 1, minor: 0 };

    /// Whether a file's version is read by this build: the same major, any minor.
    pub fn accepts(version: SchemaVersion) -> bool {
        version.major == VERSION.major
    }
}

/// The core protocol (`core-protocol.md`, `query.md`), generated from `proto/core.proto` at build
/// time.
#[allow(
    clippy::all,
    clippy::pedantic,
    reason = "generated by prost from the schema file"
)]
pub mod core {
    include!(concat!(env!("OUT_DIR"), "/yata.core.v1.rs"));

    /// The core protocol version this build speaks (`protocol-versions.md`).
    pub const VERSION: ProtocolVersion = ProtocolVersion { major: 1, minor: 0 };
}

#[cfg(test)]
mod tests {
    use prost::Message;

    use super::snapshot::{Attribute, RolledSub, Valued};

    #[test]
    fn an_unstated_roll_count_differs_from_zero_rolls() {
        let with = |rolls| RolledSub {
            valued: Some(Valued {
                attribute: Attribute::Crit.into(),
                value: 2.4,
            }),
            rolls,
        };
        assert_ne!(with(None).encode_to_vec(), with(Some(0)).encode_to_vec());
    }
}
