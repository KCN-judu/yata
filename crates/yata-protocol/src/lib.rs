#[cfg(test)]
mod tests {
    use prost::Message;

    use super::frame::{decode_all, encode};
    use super::probe::{
        AttributeValue, InnateReading, NoInnate, ProbeMessage, ReadResult, Reading, SoulRecord,
        SoulRecords, SubAttributeValue, SubAttributeValues, innate_reading::State,
        probe_message::Kind, reading::Records,
    };

    #[test]
    fn a_probe_message_survives_a_frame() {
        let soul = SoulRecord {
            soul_id: Some("a1".into()),
            suit_code: Some(30),
            star: Some(6),
            slot: Some(2),
            level: Some(15),
            main: Some(AttributeValue {
                attribute_code: 7,
                value: 57.0,
            }),
            subs: Some(SubAttributeValues {
                items: vec![SubAttributeValue {
                    attribute_code: 7,
                    value: 17.1,
                    roll_count: None,
                }],
            }),
            innate: Some(InnateReading {
                state: Some(State::None(NoInnate {})),
            }),
            locked: Some(true),
            discarded: Some(false),
            observed: None,
        };
        let message = ProbeMessage {
            kind: Some(Kind::ReadResult(ReadResult {
                request_id: 1,
                reading: Some(Reading {
                    records: Some(Records::Souls(SoulRecords {
                        souls: vec![soul],
                        ..SoulRecords::default()
                    })),
                    ..Reading::default()
                }),
            })),
        };
        let stream = encode(&message.encode_to_vec()).expect("encodable");
        let payloads = decode_all(&stream).expect("one frame");
        let [payload] = payloads.as_slice() else {
            panic!("expected one frame")
        };
        assert_eq!(ProbeMessage::decode(payload.as_slice()), Ok(message));
    }

    #[test]
    fn an_absent_roll_count_differs_from_zero_rolls() {
        let with = |roll_count| SubAttributeValue {
            attribute_code: 1,
            value: 2.4,
            roll_count,
        };
        assert_ne!(with(None).encode_to_vec(), with(Some(0)).encode_to_vec());
    }
}
