    #[test]
    fn a_fact_is_about_a_profile_and_is_some_case() {
        assert_eq!(
            decode_commit(seq(3), &with_fact(|f| f.subject = None)),
            malformed(Malformation::NoSubject)
        );
        assert_eq!(
            decode_commit(
                seq(3),
                &with_fact(|f| f.subject = Some(pb::fact::Subject::Profile(vec![1; 15])))
            ),
            malformed(Malformation::ProfileIdLength)
        );
        // A case this build does not know decodes as no case at all: in a store of a format it
        // opened, that is a broken commit, never a newer one (ADR-0032, rule 2).
        let mut fact = pb::Fact {
            subject: Some(pb::fact::Subject::Profile(P.0.to_vec())),
            body: None,
        }
        .encode_to_vec();
        fact.extend([0x9A, 0x06, 0x00]); // field 99, empty: a case of a newer schema
        let mut unknown_case = pb::Commit {
            facts: vec![],
            ..raw(&every_kind())
        }
        .encode_to_vec();
        unknown_case.extend([0x22, u8::try_from(fact.len()).expect("short")]);
        unknown_case.extend(fact);
        let e = decode_commit(seq(3), &unknown_case);
        assert_eq!(e, malformed(Malformation::NoBody));
        assert_eq!(
            e.map_err(|e| crate::wire::fact_failure(&e).code()),
            Err("store.malformed_commit")
        );
    }

