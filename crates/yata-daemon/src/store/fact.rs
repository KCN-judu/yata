//! The fact codec: commits to bytes and back, through `fact.proto` (ADR-0002, ADR-0032).
//!
//! A fact's kind and version are its `body` case (PRP-0006, option A), so a payload cannot be
//! filed under another kind. Encoding is deterministic: the same commit always yields the same
//! bytes. Decoding is bounded and strict. It never guesses: a store's format is checked when it
//! is opened, so every case and enum value of a store this build opens is one it knows, and an
//! unset case or an unknown value is a malformed commit naming its `seq` (`fact-format.md`,
//! § Reading old facts).

use std::collections::BTreeMap;

use prost::Message;
use yata_core::fact::{
    Commit, Digest, Fact, FactBody, Facts, GameAccountId, GameSoulId, Mark, NoteText, Origin,
    ProfileId, Sections, Seq, SnapshotImport,
};
use yata_core::import::ir::{Completeness, FormatTag, SchemaVersion, SectionKind, SourceFormat};

/// The fact schema, generated from `proto/fact.proto` at build time.
#[allow(
    clippy::all,
    clippy::pedantic,
    reason = "generated by prost from the schema file"
)]
mod pb {
    include!(concat!(env!("OUT_DIR"), "/yata.fact.v2.rs"));
}

/// The largest encoded commit this build writes or reads. Commits are facts, tens of bytes each;
/// a snapshot's bytes are a blob, not part of a commit.
pub const MAX_COMMIT_LEN: usize = 1 << 20;

/// What is wrong with a commit.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Malformation {
    NotACommit,
    NoOrigin,
    /// A commit holds at least one fact.
    NoFacts,
    /// The fact says what it is about in no case this build knows.
    NoSubject,
    ProfileIdLength,
    /// The fact is no case this build knows.
    NoBody,
    DigestLength,
    EmptySoulId,
    EmptyAccountId,
    /// An enum field holds its unspecified zero value.
    Unspecified(&'static str),
    /// An enum field holds a value this build does not know. A value is only added with a new
    /// store format, which this build would have refused.
    UnknownValue {
        field: &'static str,
        value: i32,
    },
    /// An import names its source format in no case this build knows.
    NoSource,
    /// An import holds no section.
    NoSections,
    /// An import lists a section twice.
    DuplicateSection,
    /// A note says neither a text nor that it is cleared.
    NoteUnset,
    /// A note gives an empty text; clearing is its own case.
    EmptyNoteText,
}

/// Why a commit could not be read back.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FactError {
    TooLarge {
        seq: Seq,
        len: usize,
    },
    Malformed {
        seq: Seq,
        what: Malformation,
    },
    /// The commit's own `seq` is not the row it was stored under.
    SeqMismatch {
        key: Seq,
        found: u64,
    },
}

/// Why a commit could not be written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EncodeError {
    TooLarge { len: usize },
}

/// Encode a commit.
pub fn encode_commit(commit: &Commit) -> Result<Vec<u8>, EncodeError> {
    let message = pb::Commit {
        seq: commit.seq.get(),
        recorded_at_unix_ms: commit.recorded_at_ms,
        origin: Some(pb::Origin {
            kind: Some(match commit.origin {
                Origin::Command { request_id } => pb::origin::Kind::CommandRequestId(request_id),
                Origin::Job { job_id } => pb::origin::Kind::JobId(job_id),
                Origin::Maintenance => pb::origin::Kind::Maintenance(pb::Maintenance {}),
            }),
        }),
        facts: commit.facts.as_slice().iter().map(encode_fact).collect(),
    };
    let bytes = message.encode_to_vec();
    if bytes.len() > MAX_COMMIT_LEN {
        return Err(EncodeError::TooLarge { len: bytes.len() });
    }
    Ok(bytes)
}

fn encode_fact(fact: &Fact) -> pb::Fact {
    use pb::fact::Body;
    let body = match &fact.body {
        FactBody::ProfileCreated {
            display_name,
            account,
        } => Body::ProfileCreatedV1(pb::ProfileCreated {
            display_name: display_name.clone(),
            account_id: account.as_ref().map(|a| a.as_str().to_owned()),
        }),
        FactBody::ProfileRenamed { display_name } => Body::ProfileRenamedV1(pb::ProfileRenamed {
            display_name: display_name.clone(),
        }),
        FactBody::ProfileRetired => Body::ProfileRetiredV1(pb::ProfileRetired {}),
        FactBody::ProfileRestored => Body::ProfileRestoredV1(pb::ProfileRestored {}),
        FactBody::SnapshotImported(i) => Body::SnapshotImportedV1(encode_import(i)),
        FactBody::SnapshotRetracted { snapshot, reason } => {
            Body::SnapshotRetractedV1(pb::SnapshotRetracted {
                snapshot: snapshot.0.to_vec(),
                reason: reason.clone(),
            })
        }
        FactBody::SoulMarked { soul, mark } => Body::SoulMarkedV1(pb::SoulMarked {
            soul_id: soul.as_str().to_owned(),
            mark: match mark {
                None => pb::Mark::None,
                Some(Mark::Keep) => pb::Mark::Keep,
                Some(Mark::Discard) => pb::Mark::Discard,
                Some(Mark::Strengthen) => pb::Mark::Strengthen,
            }
            .into(),
        }),
        FactBody::SoulNoted { soul, note } => Body::SoulNotedV1(pb::SoulNoted {
            soul_id: soul.as_str().to_owned(),
            note: Some(match note {
                Some(text) => pb::soul_noted::Note::Text(text.as_str().to_owned()),
                None => pb::soul_noted::Note::Cleared(pb::NoteCleared {}),
            }),
        }),
    };
    pb::Fact {
        subject: Some(pb::fact::Subject::Profile(fact.profile.0.to_vec())),
        body: Some(body),
    }
}

fn encode_import(i: &SnapshotImport) -> pb::SnapshotImported {
    pb::SnapshotImported {
        snapshot: i.snapshot.0.to_vec(),
        original: i.original.0.to_vec(),
        source: Some(pb::SourceFormat {
            format: Some(match i.source {
                SourceFormat::YataSnapshot(v) => {
                    pb::source_format::Format::YataSnapshot(pb::SchemaVersion {
                        major: v.major,
                        minor: v.minor,
                    })
                }
                SourceFormat::Community(tag) => pb::source_format::Format::Community(
                    match tag {
                        FormatTag::MumuSnapshotV1 => pb::FormatTag::MumuSnapshotV1,
                    }
                    .into(),
                ),
            }),
        }),
        // A BTreeMap iterates in key order, so the encoding is deterministic.
        sections: i
            .sections
            .as_map()
            .iter()
            .map(|(k, c)| pb::SectionEntry {
                kind: section_kind(*k).into(),
                completeness: completeness(*c).into(),
            })
            .collect(),
    }
}

fn section_kind(k: SectionKind) -> pb::SectionKind {
    match k {
        SectionKind::Souls => pb::SectionKind::Souls,
        SectionKind::Shikigami => pb::SectionKind::Shikigami,
        SectionKind::Presets => pb::SectionKind::Presets,
        SectionKind::Assets => pb::SectionKind::Assets,
        SectionKind::Guild => pb::SectionKind::Guild,
    }
}

fn completeness(c: Completeness) -> pb::Completeness {
    match c {
        Completeness::Complete => pb::Completeness::Complete,
        Completeness::Partial => pb::Completeness::Partial,
        Completeness::Unstated => pb::Completeness::Unstated,
    }
}

/// Decode the commit stored under `key`.
pub fn decode_commit(key: Seq, bytes: &[u8]) -> Result<Commit, FactError> {
    if bytes.len() > MAX_COMMIT_LEN {
        return Err(FactError::TooLarge {
            seq: key,
            len: bytes.len(),
        });
    }
    let malformed = |what| FactError::Malformed { seq: key, what };
    let message = pb::Commit::decode(bytes).map_err(|_| malformed(Malformation::NotACommit))?;
    if message.seq != key.get() {
        return Err(FactError::SeqMismatch {
            key,
            found: message.seq,
        });
    }
    let origin = match message.origin.and_then(|o| o.kind) {
        Some(pb::origin::Kind::CommandRequestId(request_id)) => Origin::Command { request_id },
        Some(pb::origin::Kind::JobId(job_id)) => Origin::Job { job_id },
        Some(pb::origin::Kind::Maintenance(_)) => Origin::Maintenance,
        None => return Err(malformed(Malformation::NoOrigin)),
    };
    let facts = message
        .facts
        .into_iter()
        .map(|f| decode_fact(f).map_err(malformed))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(Commit {
        seq: key,
        recorded_at_ms: message.recorded_at_unix_ms,
        origin,
        facts: Facts::new(facts).ok_or(malformed(Malformation::NoFacts))?,
    })
}

fn decode_fact(fact: pb::Fact) -> Result<Fact, Malformation> {
    use pb::fact::Body;
    let profile = match fact.subject {
        Some(pb::fact::Subject::Profile(id)) => <[u8; 16]>::try_from(id.as_slice())
            .map(ProfileId)
            .map_err(|_| Malformation::ProfileIdLength)?,
        None => return Err(Malformation::NoSubject),
    };
    let body = match fact.body.ok_or(Malformation::NoBody)? {
        Body::ProfileCreatedV1(p) => FactBody::ProfileCreated {
            display_name: p.display_name,
            account: p
                .account_id
                .map(GameAccountId::new)
                .transpose()
                .map_err(|_| Malformation::EmptyAccountId)?,
        },
        Body::ProfileRenamedV1(p) => FactBody::ProfileRenamed {
            display_name: p.display_name,
        },
        Body::ProfileRetiredV1(_) => FactBody::ProfileRetired,
        Body::ProfileRestoredV1(_) => FactBody::ProfileRestored,
        Body::SnapshotImportedV1(p) => FactBody::SnapshotImported(decode_import(p)?),
        Body::SnapshotRetractedV1(p) => FactBody::SnapshotRetracted {
            snapshot: digest(&p.snapshot)?,
            reason: p.reason,
        },
        Body::SoulMarkedV1(p) => FactBody::SoulMarked {
            soul: soul(p.soul_id)?,
            mark: match known::<pb::Mark>("mark", p.mark)? {
                pb::Mark::None => None,
                pb::Mark::Keep => Some(Mark::Keep),
                pb::Mark::Discard => Some(Mark::Discard),
                pb::Mark::Strengthen => Some(Mark::Strengthen),
                pb::Mark::Unspecified => return Err(Malformation::Unspecified("mark")),
            },
        },
        Body::SoulNotedV1(p) => FactBody::SoulNoted {
            soul: soul(p.soul_id)?,
            note: match p.note {
                Some(pb::soul_noted::Note::Text(text)) => {
                    Some(NoteText::new(text).ok_or(Malformation::EmptyNoteText)?)
                }
                Some(pb::soul_noted::Note::Cleared(_)) => None,
                None => return Err(Malformation::NoteUnset),
            },
        },
    };
    Ok(Fact { profile, body })
}

fn decode_import(p: pb::SnapshotImported) -> Result<SnapshotImport, Malformation> {
    let source = match p.source.and_then(|s| s.format) {
        Some(pb::source_format::Format::YataSnapshot(v)) => {
            SourceFormat::YataSnapshot(SchemaVersion {
                major: v.major,
                minor: v.minor,
            })
        }
        Some(pb::source_format::Format::Community(tag)) => {
            SourceFormat::Community(match known::<pb::FormatTag>("format_tag", tag)? {
                pb::FormatTag::MumuSnapshotV1 => FormatTag::MumuSnapshotV1,
                pb::FormatTag::Unspecified => return Err(Malformation::Unspecified("format_tag")),
            })
        }
        None => return Err(Malformation::NoSource),
    };
    let mut sections = BTreeMap::new();
    for e in p.sections {
        let kind = match known::<pb::SectionKind>("section_kind", e.kind)? {
            pb::SectionKind::Souls => SectionKind::Souls,
            pb::SectionKind::Shikigami => SectionKind::Shikigami,
            pb::SectionKind::Presets => SectionKind::Presets,
            pb::SectionKind::Assets => SectionKind::Assets,
            pb::SectionKind::Guild => SectionKind::Guild,
            pb::SectionKind::Unspecified => return Err(Malformation::Unspecified("section_kind")),
        };
        let c = match known::<pb::Completeness>("completeness", e.completeness)? {
            pb::Completeness::Complete => Completeness::Complete,
            pb::Completeness::Partial => Completeness::Partial,
            pb::Completeness::Unstated => Completeness::Unstated,
            pb::Completeness::Unspecified => return Err(Malformation::Unspecified("completeness")),
        };
        if sections.insert(kind, c).is_some() {
            return Err(Malformation::DuplicateSection);
        }
    }
    Ok(SnapshotImport {
        snapshot: digest(&p.snapshot)?,
        original: digest(&p.original)?,
        source,
        sections: Sections::new(sections).ok_or(Malformation::NoSections)?,
    })
}

fn known<E: TryFrom<i32>>(field: &'static str, value: i32) -> Result<E, Malformation> {
    E::try_from(value).map_err(|_| Malformation::UnknownValue { field, value })
}

fn digest(bytes: &[u8]) -> Result<Digest, Malformation> {
    <[u8; 32]>::try_from(bytes)
        .map(Digest)
        .map_err(|_| Malformation::DigestLength)
}

fn soul(id: String) -> Result<GameSoulId, Malformation> {
    GameSoulId::new(id).map_err(|_| Malformation::EmptySoulId)
}

